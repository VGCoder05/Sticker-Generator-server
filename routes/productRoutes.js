import { Router } from 'express';
import { listProducts, createProduct, updateProduct, deleteProduct, previewProductImport, commitProductImport } from '../controllers/productController.js';
const router = Router();
router.get('/', listProducts);
router.post('/', createProduct);
router.post('/import-preview', previewProductImport);
router.post('/import', commitProductImport);
router.patch('/:id', updateProduct);
router.delete('/:id', deleteProduct);
export default router;
